#!/usr/bin/env python
"""
Build analysis/instances/utahps_daily -- a working copy of data/utahps_daily.

Why a copy at all: HERSS writes its output files into the dataset directory's
own output/ subdirectory, and data/*/output/ is version controlled (CLAUDE.md
section 5). Running the shipped dataset in place would dirty the tracked tree on
every evaluation. Nothing under data/ is touched.

All five input files keep their original names and are byte-for-byte copies,
including global_utahps_daily.txt -- which is what makes STARTSTATEFILE,
PRICEFILE and friends resolve without editing anything.

The only generated file is start_state_utahps.txt: the four channels' linear
reservoir storages are initialised at the steady state for the flow they
actually carry, instead of the 0.001/0.002/0.003 placeholders in the shipped
file.

    cascadedreservoirs.cpp:41   k_res = K_TRAVELTIME_HOURS*3600 / N_CASCADE_LINRES
    cascadedreservoirs.cpp:106  S_next = S*exp(-dt/k_res) + k_res*(1-exp)*q_in

so under constant inflow Q the steady state is S = k_res * Q in every linear
reservoir of the cascade.

Unlike res_casc_A, this is NOT value-neutral in principle. There every channel
sat downstream of the only power station, so nothing they held could ever be
turbined. Here VANAROSEN, GRONANI and DALSANA sit BETWEEN stations: water parked
in them is water TOPPSY or KROKNESVATN does not have, and the placeholder
storages are 0.006 Mm3 of extra water injected into the system at t=0. The dVF
is reported rather than asserted to be zero; the point of the steady-state
initialisation is that the channels start in the state the routing model would
have put them in, not that it changes nothing.

Reservoir init_fr (0.7 / 0.8 / 0.9 / 0.66) is copied unchanged.
"""

import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import nodefiles  # noqa: E402
import params3  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "data", "utahps_daily")
DST = os.path.join(REPO, "analysis", "instances", "utahps_daily")
HERSS_EXE = os.path.join(REPO, "src", "herss.exe")

VERBATIM = ["global_utahps_daily.txt", "topology_utahps.txt",
            "pricefile_utahps.txt", "inflowseries_utahps.txt",
            "actions_utahps.txt"]

STATEFILE = "start_state_utahps.txt"
RIVERSYSTEM_OUT = "riversystem_uTAHPS_output.txt"

HEADER = """\
##########################################################################
# Statefile utahps_daily -- working copy of data/utahps_daily
# Generated by analysis/full_cascade/build_utahps_daily.py -- do not hand-edit.
#
# Reservoir init_fr copied unchanged from the shipped state file.
# Channel linear-reservoir storages replaced by the steady state
#   S = k_res * Q,   k_res = K_TRAVELTIME_HOURS*3600 / N_CASCADE_LINRES
# (cascadedreservoirs.cpp:41,106) for the mean flow each channel carries under
# the shipped actions_utahps.txt.
##########################################################################

# NODE RESERVOIR IDNR NAME INIT_RES_FR
"""


def copy_verbatim():
    os.makedirs(os.path.join(DST, "output"), exist_ok=True)
    for fn in VERBATIM:
        shutil.copyfile(os.path.join(SRC, fn), os.path.join(DST, fn))


def run_cli(cwd=DST):
    r = subprocess.run([HERSS_EXE, "global_utahps_daily.txt"], cwd=cwd,
                       capture_output=True, text=True, timeout=300)
    if r.returncode != 0:
        raise RuntimeError(f"herss.exe failed ({r.returncode}):\n{r.stdout}\n{r.stderr}")
    return r


def write_start_state(p, mean_q):
    """mean_q: {channel_idnr: mean up_inflow m3/s}."""
    lines = [HEADER]
    for r in p.reservoirs:
        lines.append(f"NODE RESERVOIR {r.idnr} {r.name} {r.init_fr}\n")
    lines.append("\n# NODE PSTATION IDNR NAME MWh\n")
    for s in p.stations:
        lines.append(f"NODE PSTATION {s.idnr} {s.name} 0.0\n")
    lines.append("\n# NODE CHANNEL IDNR NAME LINRES1_Mm3 ... LINRES{N}_Mm3\n")
    for c in p.channels:
        q = mean_q[c.idnr]
        s_Mm3 = c.k_res_seconds * q / 1e6
        lines.append(f"# {c.name}: k_res = {c.k_res_seconds:.1f} s, "
                     f"mean Q = {q:.4f} m3/s -> S = {s_Mm3:.8f} Mm3 per linres\n")
        lines.append(f"NODE CHANNEL {c.idnr} {c.name} " +
                     " ".join(f"{s_Mm3:.8f}" for _ in range(c.n_linres)) + "\n")
    lines.append("\n## END\n")
    with open(os.path.join(DST, STATEFILE), "w") as f:
        f.write("".join(lines))


def read_channel_up_inflow(idnr, name):
    """Mean Up_Inflow [m3/s] from the channel's node output file (channel.cpp:444-453)."""
    node = nodefiles.read_node_file(
        os.path.join(DST, "output", f"node{idnr}_{name}.txt"))
    vals = nodefiles.column(node, "Up_Inflow")
    return sum(vals) / len(vals)


def read_riversystem_scalars():
    return nodefiles.read_riversystem(os.path.join(DST, "output", RIVERSYSTEM_OUT))


def check_terminal_term(p, scalars):
    """
    The chain-equivalent derivation, checked against the simulator's own
    tot_remaining_MWh rather than argued for. See params3.chain_equivalents.

    The node file reports Res_Mm3, not the active volume, so the LRW/HRW clip of
    reservoir.cpp:664-677 is reapplied here.
    """
    active = {}
    for r in p.reservoirs:
        node = nodefiles.read_node_file(
            os.path.join(DST, "output", f"node{r.idnr}_{r.name}.txt"))
        end_Mm3 = nodefiles.column(node, "Res_Mm3")[-1]
        fr = (end_Mm3 - r.filling_at_lrw_Mm3) / r.active_capacity_Mm3
        active[r.idnr] = min(max(fr, 0.0), 1.0) * r.active_capacity_Mm3
    mwh = sum(p.chain_equivalent[i] * v * 1000.0 for i, v in active.items())
    return active, mwh, scalars["tot_remaining_MWh"]


def main():
    copy_verbatim()

    # Pass 1: shipped placeholder storages, to measure what each channel carries.
    shutil.copyfile(os.path.join(SRC, STATEFILE), os.path.join(DST, STATEFILE))
    run_cli()
    vf_placeholder = read_riversystem_scalars()["valuefunction_Euro"]

    p = params3.get()
    mean_q = {c.idnr: read_channel_up_inflow(c.idnr, c.name) for c in p.channels}
    print("mean channel up_inflow under shipped actions_utahps.txt [m3/s]:")
    for c in p.channels:
        print(f"  node {c.idnr:2d} {c.name:12s} N={c.n_linres} "
              f"K={c.K_traveltime_hours:.0f}h  mean Q = {mean_q[c.idnr]:8.4f}  "
              f"-> S = {c.k_res_seconds * mean_q[c.idnr] / 1e6:.8f} Mm3/linres")

    # Pass 2: steady-state storages. Rebuild params so init_storage_Mm3 is current.
    write_start_state(p, mean_q)
    params3._CACHE.clear()
    p = params3.get()
    run_cli()
    sc = read_riversystem_scalars()

    print(f"\nVF with shipped placeholder channel init : {vf_placeholder:.4f}")
    print(f"VF with steady-state channel init        : {sc['valuefunction_Euro']:.4f}")
    print(f"dVF                                      : "
          f"{sc['valuefunction_Euro'] - vf_placeholder:+.4f}")

    print("\nglobal water balance:")
    for k in ("start_water_Mm3", "inflow_volume_Mm3", "outflow_Mm3",
              "end_water_Mm3", "waterbalance"):
        print(f"  {k:20s} = {sc[k]:.6f}")

    active, mwh_derived, mwh_herss = check_terminal_term(p, sc)
    print("\nterminal term cross-check (chain equivalents vs simulator):")
    for r in p.reservoirs:
        print(f"  {r.name:12s} active {active[r.idnr]:10.4f} Mm3 x "
              f"{p.chain_equivalent[r.idnr]:.2f} kWh/m3 = "
              f"{p.chain_equivalent[r.idnr] * active[r.idnr] * 1000.0:12.3f} MWh")
    print(f"  derived total  = {mwh_derived:.3f} MWh")
    print(f"  tot_remaining_MWh (HERSS) = {mwh_herss:.3f} MWh")
    print(f"  relative difference = {abs(mwh_derived - mwh_herss) / mwh_herss:.3e}")

    ok = True
    if abs(sc["waterbalance"]) > 1e-6:
        print("FAIL: global water balance does not close", file=sys.stderr)
        ok = False
    if abs(mwh_derived - mwh_herss) / mwh_herss > 1e-4:
        print("FAIL: chain-equivalent derivation does not reproduce "
              "tot_remaining_MWh", file=sys.stderr)
        ok = False
    if not ok:
        return 1

    print("\nOK: instance built, water balance closes, terminal term verified.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
